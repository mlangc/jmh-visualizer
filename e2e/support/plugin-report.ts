import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const FIXTURES = path.join(__dirname, '..', 'fixtures');
const BUILD_DIR = path.resolve(process.env.APP_BUILD_DIR ?? '../build');

/**
 * The `provided.js` that gradle-jmh-report's `JmhReportTask.generateReport()` writes
 * (https://github.com/mlangc/gradle-jmh-report, checked at commit
 * 694e795425f47de3bda7a595cedc101f6cdf4e1a): a header comment, the two globals jmh-visualizer
 * reads, and the result file's content pasted in verbatim, line by line, as the value
 * keyed by the file's base name. Keep this in step with the task, not with what we'd
 * like the contract to be -- the point is to render what the plugin really emits.
 */
export function pluginProvidedJs(resultFileName: string, resultJson: string): string {
  const runName = removeExtension(resultFileName);
  return [
    '// provided.js - generated by gradle-jmh-report, 2026-01-01 00:00:00.000',
    '',
    `var providedBenchmarks = ['${runName}'];`,
    '',
    'var providedBenchmarkStore = {',
    `'${runName}': `,
    ...resultJson.split(/\r?\n/),
    '};',
    ''
  ].join('\n');
}

/** The name the plugin gives the run: the result file's name up to its last dot. */
export function pluginRunName(resultFileName: string): string {
  return removeExtension(resultFileName);
}

function removeExtension(fileName: string): string {
  const dot = fileName.lastIndexOf('.');
  return dot < 0 ? fileName : fileName.substring(0, dot);
}

export function readFixture(fixtureName: string): string {
  return fs.readFileSync(path.join(FIXTURES, fixtureName), 'utf8');
}

/**
 * Lays out a report the way the plugin does: the built app, unpacked into a folder of
 * its own, with `provided.js` overwritten. Returns the `file://` URL of its `index.html`,
 * since that is how people open these reports -- no server involved.
 */
export function createPluginReport(dir: string, resultFileName: string, resultJson: string): string {
  fs.cpSync(BUILD_DIR, dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'provided.js'), pluginProvidedJs(resultFileName, resultJson), 'utf8');
  return pathToFileURL(path.join(dir, 'index.html')).href;
}

export { BUILD_DIR };
